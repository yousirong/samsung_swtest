// ====================================================================
// BOJ 6603 - 로또
//
//   k개의 수가 오름차순으로 주어지면, 그중 6개를 고르는 모든 방법을 사전순으로 출력한다.
//   k = 0 이면 입력이 끝난다. 테스트 케이스 사이에는 빈 줄을 하나 넣는다.
//
//   순서를 구분하지 않으므로 조합이다.
//   start를 두고 다음 시작값을 i + 1로 넘기면 항상 오름차순으로만 뽑히고,
//   입력이 이미 오름차순이라 별도 정렬 없이 사전순 출력이 된다.
// ====================================================================

#include <stdio.h>

#define MAX (13 + 3)

int N, M;

int num_of_cases[MAX];   // 만들고 있는 조합 (6칸)
int number[MAX];         // 입력으로 주어진 수들 (이미 오름차순)

// 입력 (N == 0 이면 호출한 쪽에서 종료 판단)
void input()
{
	scanf("%d", &N);

	for (int i = 1; i <= N; i++)
		scanf("%d", &number[i]);
}

// 완성된 조합 한 줄 출력
void printCases()
{
	for (int i = 0; i < 6; i++)
		printf("%d ", num_of_cases[i]);
	putchar('\n');
}

// 재귀로 조합 생성
//   depth : 지금까지 몇 개 뽑았는지
//   start : 이번에 뽑을 수 있는 최소 인덱스
void DFS(int depth, int start)
{
	// 6개를 다 뽑았으면 한 경우 완성
	if (depth == 6)
	{
		printCases();
		return;
	}

	for (int i = start; i <= N; i++)
	{
		num_of_cases[depth] = number[i];

		// 다음은 반드시 i보다 뒤에서 -> 같은 조합이 순서만 바꿔 다시 나오지 않는다
		DFS(depth + 1, i + 1);
	}
}

int main()
{
	// 입력이 여러 줄 들어오고 0으로 끝나는 형식
	while (1)
	{
		input();
		if (N == 0) break;   // 0이면 종료

		DFS(0, 1);

		putchar('\n');       // 테스트 케이스 사이 빈 줄
	}

	return 0;
}

// ====================================================================
// BOJ 10819 - 차이를 최대로
//
//   N개의 수를 적절히 재배열해서 아래 식을 최대로 만든다.
//
//     |A[0] - A[1]| + |A[1] - A[2]| + ... + |A[N-2] - A[N-1]|
//
//   N <= 8 이라 가능한 배열이 최대 8! = 40,320가지뿐이다.
//   따라서 규칙을 찾지 않고 모든 순열을 만들어 값을 재 보는 완전탐색으로 충분하다.
//   (배치 순서가 곧 답이므로 조합이 아니라 순열이어야 한다)
//
//   순열이 하나 완성될 때마다 점수를 계산해 최댓값만 갱신한다.
// ====================================================================

#include <stdio.h>
#include <stdbool.h>

#define MAX (8 + 3)

int N;                   // 수의 개수

int num_of_cases[MAX];   // 현재 만들고 있는 배열(순열)
bool visit[MAX];         // i번째 입력 수를 이미 배치했는지
int number[MAX];         // 입력 수들 (여기서는 0-based로 저장)

int maxAnswer;           // 지금까지의 최댓값

// ---------------------------
// 디버그용: 현재 순열 출력
// ---------------------------
void printCases()
{
	for (int i = 0; i < N; i++)
		printf("%d ", num_of_cases[i]);
	putchar('\n');
}

// ---------------------------
// 절댓값 (stdlib.h 없이 직접 구현)
// ---------------------------
int abs(int x)
{
	return (x > 0) ? x : -x;
}

// ---------------------------
// 현재 배열의 점수 계산
//   |A[0]-A[1]| + |A[1]-A[2]| + ... + |A[N-2]-A[N-1]|
// 이웃한 쌍이 N-1개이므로 i는 N-2까지만 돈다.
// ---------------------------
int calculate()
{
	int sum = 0;

	for (int i = 0; i < N - 1; i++)
		sum += abs(num_of_cases[i] - num_of_cases[i + 1]);

	return sum;
}

// ---------------------------
// 재귀로 순열 생성
//   depth : 지금 채우려는 자리 번호
// ---------------------------
void DFS(int depth)
{
	// 자리를 다 채웠다 = 배열 하나가 완성됐다
	if (depth == N)
	{
		// 완성된 배열의 점수를 재고 최댓값만 남긴다
		int tmp = calculate();

		if (maxAnswer < tmp)
			maxAnswer = tmp;

		return;
	}

	// 아직 배치하지 않은 수 중 하나를 이 자리에 놓는다
	for (int i = 0; i < N; i++)
	{
		if (visit[i] == true)
			continue;

		num_of_cases[depth] = number[i];

		visit[i] = true;     // 사용 중

		DFS(depth + 1);

		visit[i] = false;    // 반납 (백트래킹)
	}
}

// ---------------------------
// 메인
// ---------------------------
int main()
{
	scanf("%d", &N);

	// 수 입력 (0-based)
	for (int i = 0; i < N; i++)
		scanf("%d", &number[i]);

	// 식의 값은 항상 0 이상이므로 -1로 시작하면 반드시 갱신된다
	maxAnswer = -1;

	DFS(0);

	printf("%d\n", maxAnswer);

	return 0;
}
