/*
	[BOJ] 15652 N과 M (4) / 15657 N과 M (8) - 중복조합
	https://www.acmicpc.net/problem/15652
	https://www.acmicpc.net/problem/15657

	■ 이 파일에 대하여
	  두 문제의 풀이가 아래위로 나란히 들어 있는 정리용 파일이다.
	  main과 전역 변수가 각각 하나씩 있으므로 한꺼번에 컴파일되지는 않는다.
	  필요한 쪽만 남기고 다른 쪽은 주석 처리해서 쓴다.

	■ 두 문제의 공통 주제 : 중복조합
	    - 중복 허용 : 같은 값을 몇 번이든 다시 골라도 된다
	    - 순서 무시 : 1 2 와 2 1 은 같은 경우이므로 하나만 출력한다

	  "순서를 무시한다"를 코드로 옮기는 방법이 이 문제의 전부다.
	  같은 조합을 여러 순서로 만들어 놓고 나중에 거르는 게 아니라,
	  애초에 "비내림차순(앞 <= 뒤)인 것만" 만들면 각 조합이 정확히 한 번씩만 생성된다.

	  이를 위해 재귀에 start 인자를 추가한다.

	    for (i = start; i <= N; i++)  ->  이번 자리에 고를 수 있는 최소값이 start
	    DFS(depth + 1, i)             ->  다음 자리도 i부터 가능 (같은 값 재선택 허용)

	  여기서 다음 start를 i로 넘기느냐 i+1로 넘기느냐가 중복조합과 조합을 가른다.

	    중복조합 : DFS(depth + 1, i)      ->  a <= b <= c   (15652 / 15657, 이 파일)
	    조합     : DFS(depth + 1, i + 1)  ->  a <  b <  c   (15650 / 15655, 31번 파일)

	■ 두 문제의 차이
	    15652 : 후보가 1 ~ N 이라 i를 그대로 담는다.
	    15657 : 후보가 입력으로 주어진 N개의 수라서 number[i]를 담는다.
	            사전순 출력을 위해 입력을 먼저 오름차순 정렬해 둔다.
	            (정렬해 둬야 "인덱스가 커진다 = 값이 커지거나 같다"가 성립해서
	             비내림차순 출력이 보장된다)
*/

// ====================================================================
// BOJ 15652 - N과 M (4)
//
//   1부터 N까지의 수 중에서 중복을 허용해 M개를 고른다.
//   고른 수열은 비내림차순이어야 한다.
//
//   예) N = 3, M = 2
//       1 1 / 1 2 / 1 3 / 2 2 / 2 3 / 3 3   (총 3H2 = 4C2 = 6가지)
// ====================================================================

#include <stdio.h>

#define MAX (7 + 3)

int N, M;
int num_of_cases[MAX];   // 만들고 있는 수열

// 완성된 수열 한 줄 출력
void printCases()
{
	for (int i = 0; i < M; i++)
		printf("%d ", num_of_cases[i]);
	putchar('\n');
}

// 재귀로 중복조합 생성
//   depth : 지금 채우려는 자리 번호 (0부터)
//   start : 이번 자리에 고를 수 있는 최소 숫자
void DFS(int depth, int start)
{
	// M개를 다 골랐으면 한 경우 완성
	if (depth == M)
	{
		printCases();
		return;
	}

	// 앞에서 고른 값보다 작은 값은 보지 않는다.
	// 이 제한 덕분에 항상 비내림차순이 되고, 같은 조합이 두 번 만들어지지 않는다.
	for (int i = start; i <= N; i++)
	{
		num_of_cases[depth] = i;

		// 다음 자리의 시작값을 i로 넘긴다 = 같은 값을 다시 골라도 된다 (중복 허용)
		// i + 1로 넘기면 그 순간 일반 조합이 된다.
		DFS(depth + 1, i);
	}
}

int main()
{
	scanf("%d %d", &N, &M);

	DFS(0, 1);   // 0번째 자리부터, 첫 후보는 1부터

	return 0;
}

// ====================================================================
// BOJ 15657 - N과 M (8)
//
//   입력으로 주어진 N개의 수 중에서 중복을 허용해 M개를 고른다.
//   고른 수열은 비내림차순이어야 하고, 출력은 사전순이어야 한다.
//
//   예) 입력 숫자 9 7 1  ->  정렬 후 1 7 9, M = 2 이면
//       1 1 / 1 7 / 1 9 / 7 7 / 7 9 / 9 9
//
//   15652와 재귀 구조는 같고, 넣는 값이 i 대신 number[i]라는 점만 다르다.
// ====================================================================

#include <stdio.h>

#define MAX (7 + 3)

int N, M;

int num_of_cases[MAX];   // 만들고 있는 수열
int number[MAX];         // 후보로 주어진 수들 (1-based로 저장)

// 완성된 수열 한 줄 출력
void printCases()
{
	for (int i = 0; i < M; i++)
		printf("%d ", num_of_cases[i]);
	putchar('\n');
}

// 재귀로 중복조합 생성
//   depth : 지금 채우려는 자리 번호
//   start : 이번 자리에 고를 수 있는 최소 "인덱스"
void DFS(int depth, int start)
{
	if (depth == M)
	{
		printCases();
		return;
	}

	for (int i = start; i <= N; i++)
	{
		// 15652와 유일하게 다른 줄 : 인덱스가 아니라 실제 입력값을 담는다
		num_of_cases[depth] = number[i];

		// 인덱스 기준으로 i부터 다시 고를 수 있다 (중복 허용)
		DFS(depth + 1, i);
	}
}

int main()
{
	scanf("%d %d", &N, &M);

	// 후보 수 입력
	for (int i = 1; i <= N; i++)
		scanf("%d", &number[i]);

	// 오름차순 정렬 (선택 정렬)
	// 정렬해 둬야 "인덱스 증가 = 값이 작아지지 않음"이 되어
	// 비내림차순 조건과 사전순 출력이 동시에 만족된다.
	for (int i = 1; i <= N - 1; i++)
	{
		for (int k = i + 1; k <= N; k++)
		{
			if (number[i] > number[k])
			{
				int tmp = number[i];
				number[i] = number[k];
				number[k] = tmp;
			}
		}
	}

	DFS(0, 1);

	return 0;
}
