/*
	[정리] 경우의 수 4종 - 중복순열 / 중복조합 / 조합 / 순열

	■ 이 파일의 목적
	  백준 문제 풀이가 아니라, 완전탐색의 기본이 되는 네 가지 나열 방식을
	  "가장 단순한 형태(4개 중 3개를 뽑는 3중 for문)"로 나란히 비교해 보는 예제다.
	  각 블록의 if (1) / if (0)을 바꿔 가며 하나씩 켜서 출력을 눈으로 확인하면 된다.
	  현재는 1번(중복순열)만 켜져 있다.

	■ 네 가지 구분 기준
	  두 가지 질문으로 갈린다.

	    (1) 순서를 구분하는가?   (1 2 3 과 3 2 1 이 다른 경우인가)
	    (2) 같은 수를 또 써도 되는가?

	                순서 구분 O        순서 구분 X
	    중복 허용 O   중복순열 (4^3=64)   중복조합 (4H3=20)
	    중복 허용 X   순열     (4P3=24)   조합     (4C3=4)

	■ 구현 패턴 (외우면 그대로 쓰인다)
	    중복순열 : for(b = 1     ...)        // 아무 제약 없음
	    중복조합 : for(b = a     ...)        // 앞의 수 "이상"  -> a <= b <= c 로 강제
	    조합     : for(b = a + 1 ...)        // 앞의 수 "초과"  -> a <  b <  c 로 강제
	    순열     : for(b = 1 ...) + visit[]  // 이미 쓴 수는 건너뛰기

	  순서를 없애는(= 중복 집계를 막는) 방법이 "항상 증가하는 순서로만 뽑기"라는 점이 핵심이다.
	  a <= b <= c 로만 뽑으면 {1,1,2}는 한 번만 나오고 (1,2,1) (2,1,1)은 아예 생성되지 않는다.

	■ 재귀와의 관계
	  실전에서는 뽑는 개수가 입력으로 바뀌므로 for문을 겹쳐 쓸 수 없고 재귀로 바꾼다.
	  이때 위 표의 "다음 for의 시작값"이 그대로 재귀 함수의 인자로 넘어간다.
	    중복조합 -> rec(idx + 1, start = 현재 값)
	    조합     -> rec(idx + 1, start = 현재 값 + 1)
	  같은 파일 세트의 28 ~ 33번이 그 재귀 버전이다.
*/

#include <stdio.h>
#include <stdbool.h>

int main()
{
	int count;   // 출력 줄 번호

	// ----------------------------------------
	// 1. 중복순열 (4 Pi 3) : 순서 O, 중복 O
	// ----------------------------------------
	// 각 자리에 1~4가 아무 제약 없이 들어간다.
	// 총 4 * 4 * 4 = 64가지.
	//   예) 1 1 1, 1 2 1, 2 1 1 모두 서로 다른 경우로 출력된다.
	if (1)
	{
		count = 1;

		for (int a = 1; a <= 4; a++)              // 첫째 자리
			for (int b = 1; b <= 4; b++)          // 둘째 자리 (제약 없음)
				for (int c = 1; c <= 4; c++)      // 셋째 자리 (제약 없음)
					printf("%d] %d %d %d\n", count++, a, b, c);
	}

	// ----------------------------------------
	// 2. 중복조합 (4 H 3) : 순서 X, 중복 O
	// ----------------------------------------
	// 순서를 없애기 위해 a <= b <= c 인 조합만 만든다.
	// 그래서 다음 for문의 시작값이 "앞의 값"이 된다.
	// 총 4H3 = 6C3 = 20가지.
	//   예) 1 1 2 는 출력되지만, 같은 집합인 1 2 1 / 2 1 1 은 생성되지 않는다.
	if (0)
	{
		count = 1;

		for (int a = 1; a <= 4; a++)              // 첫째 수
			for (int b = a; b <= 4; b++)          // b >= a
				for (int c = b; c <= 4; c++)      // c >= b
					printf("%d] %d %d %d\n", count++, a, b, c);
	}

	// ----------------------------------------
	// 3. 조합 (4 C 3) : 순서 X, 중복 X
	// ----------------------------------------
	// 중복조합에서 등호만 빼면 된다. a < b < c 인 것만 만든다.
	// 다음 for문의 시작값이 "앞의 값 + 1"이다.
	// 총 4C3 = 4가지 (1 2 3 / 1 2 4 / 1 3 4 / 2 3 4).
	if (0)
	{
		count = 1;

		for (int a = 1; a <= 4; a++)              // 첫째 수
			for (int b = a + 1; b <= 4; b++)      // b > a
				for (int c = b + 1; c <= 4; c++)  // c > b
					printf("%d] %d %d %d\n", count++, a, b, c);
	}

	// ----------------------------------------
	// 4. 순열 (4 P 3) : 순서 O, 중복 X
	// ----------------------------------------
	// 순서를 구분하므로 범위는 항상 1~4 전체를 돌되,
	// "이미 쓴 수"만 걸러야 한다. 이 역할을 visit 배열이 한다.
	// 총 4P3 = 24가지.
	//
	// visit는 반드시 다음 두 동작이 짝을 이뤄야 한다.
	//   들어가기 전 : visit[x] = true   (내가 쓰는 중)
	//   나온 뒤     : visit[x] = false  (다음 후보를 위해 반납 = 백트래킹)
	// 반납을 빼먹으면 뒤쪽 경우의 수가 통째로 사라진다.
	if (0)
	{
		count = 1;

		bool visit[5] = { 0 };  // 1~4 사용 여부 (인덱스 0은 쓰지 않음)

		for (int a = 1; a <= 4; a++)
		{
			visit[a] = true;   // a 사용 중

			for (int b = 1; b <= 4; b++)
			{
				// a가 이미 쓴 수라면 건너뛴다
				if (visit[b] == true) continue;

				visit[b] = true;  // b 사용 중

				for (int c = 1; c <= 4; c++)
				{
					// a, b가 이미 쓴 수라면 건너뛴다
					if (visit[c] == true) continue;

					// 여기 온 a, b, c는 서로 다른 값이 보장된다
					printf("%d] %d %d %d\n", count++, a, b, c);
				}

				visit[b] = false;  // b 반납 (백트래킹)
			}

			visit[a] = false;  // a 반납 (백트래킹)
		}
	}

	return 0;
}
