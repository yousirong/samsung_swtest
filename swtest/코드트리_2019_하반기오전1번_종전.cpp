/*
	[코드트리] 2019 하반기 오전 1번 - 종전
	https://www.codetree.ai/training-field/frequent-problems/problems/war-finish

	■ 문제 요약
	  N x N 격자의 각 칸에 인구 수가 적혀 있다.
	  기준점 (sr, sc)와 두 길이 d1, d2를 정하면 아래 마름모 경계선이 그려진다.

	      (sr, sc) -> (sr+d1, sc-d1)          왼쪽 아래로
	      (sr, sc) -> (sr+d2, sc+d2)          오른쪽 아래로
	      (sr+d1, sc-d1) -> (sr+d1+d2, sc-d1+d2)
	      (sr+d2, sc+d2) -> (sr+d1+d2, sc+d2-d1)

	  이 마름모(경계선과 그 안쪽)가 한 구역이고, 나머지가 마름모를 기준으로
	  좌상 / 우상 / 좌하 / 우하 네 구역으로 나뉘어 총 5개 구역이 된다.
	  각 구역 인구의 합을 구했을 때 (최대 - 최소)를 가장 작게 만드는 값을 출력한다.

	  (백준 17779 "게리맨더링 2"와 같은 문제다)

	■ 풀이 방침 : 가능한 (sr, sc, d1, d2)를 전부 시도
	  N이 20 이하라 네 값의 조합이 많아야 수만 가지 수준이다.
	  각 조합마다 구역을 실제로 칠하고 합을 재도 충분히 빠르다.

	  유효성 검사는 "마름모의 네 꼭짓점이 격자 안에 있는가"만 보면 된다.
	  격자 바깥을 -1로 채워 뒀기 때문에 꼭짓점 좌표의 값이 -1인지만 확인하면 끝난다.
	  d1, d2를 1부터 늘리다가 꼭짓점이 밖으로 나가는 순간 그 방향은 더 볼 필요가 없어 break 한다.

	■ 구역 칠하기 (calculate)
	  순서가 중요하다. 마름모(1번)를 먼저 칠하고, 나머지 네 구역이 그것을 피해 가게 만든다.

	  1) 마름모 채우기
	     행을 한 줄씩 내려가며 [start, end] 구간을 통째로 칠한다.
	     처음엔 (sr, sc) 한 칸에서 시작해 왼쪽 경계는 왼쪽으로, 오른쪽 경계는 오른쪽으로 벌어진다.
	     왼쪽이 꼭짓점 열 sc-d1에 닿으면 그때부터 오른쪽으로 좁혀지고,
	     오른쪽이 sc+d2에 닿으면 왼쪽으로 좁혀진다.
	     이렇게 하면 경계선뿐 아니라 내부까지 한 번에 칠해진다.

	  2) 나머지 네 구역은 문제에 적힌 부등식을 그대로 옮긴다.

	       2번(좌상) : r <= sr+d1-1,      c <= sc
	       3번(우상) : r <= sr+d2,        c >= sc+1
	       4번(좌하) : r >= sr+d1,        c <= sc-d1+d2-1
	       5번(우하) : r >= sr+d2+1,      c >= sc-d1+d2

	■ break 와 continue 를 나눠 쓰는 이유
	  왼쪽 구역(2번, 4번)은 행을 왼쪽부터 훑다가 마름모를 만나면 그 행은 거기서 끝이다.
	  마름모 오른쪽은 다른 구역 몫이므로 break로 그 행을 빠져나온다.

	  오른쪽 구역(3번, 5번)은 마름모를 지나 더 오른쪽에도 자기 칸이 남아 있다.
	  그래서 마름모 칸만 건너뛰고(continue) 계속 오른쪽을 봐야 한다.

	  이 차이를 바꿔 쓰면 구역이 잘못 칠해진다.

	■ 합산
	  area[r][c]를 인덱스로 삼아 sum[area]에 인구를 더한다.
	  어느 구역에도 속하지 않은 칸은 없어야 정상이지만, 혹시 0이 남더라도
	  sum[0]에 모여 최대/최소 계산(1~5만 확인)에는 끼지 않는다.
*/

#include <stdio.h>

#define MAX (20 + 5)
#define INF (0x7fff0000)

int T;

int N;
int MAP[MAX][MAX];   // 인구 수 (격자 바깥은 -1)
int minAnswer;       // (최대 구역 - 최소 구역)의 최솟값

// ---------------------------
// 입력
// ---------------------------
void input()
{
	scanf("%d", &N);

	// 격자 바깥을 -1로 채운다.
	// 마름모 꼭짓점이 격자를 벗어났는지 판정할 때
	// 좌표 비교 대신 값이 -1인지만 보면 되어 코드가 짧아진다.
	for (int r = 0; r <= N + 1; r++)
	{
		for (int c = 0; c <= N + 1; c++)
		{
			MAP[r][c] = -1;
		}
	}

	for (int r = 1; r <= N; r++)
	{
		for (int c = 1; c <= N; c++)
		{
			scanf("%d", &MAP[r][c]);
		}
	}
}

// ---------------------------
// 디버그용 출력 (area 배열을 넘겨 구역 모양을 눈으로 확인할 때 쓴다)
// ---------------------------
void printMap(int map[MAX][MAX])
{
	for (int r = 1; r <= N; r++)
	{
		for (int c = 1; c <= N; c++)
			printf("%d ", map[r][c]);
		putchar('\n');
	}
	putchar('\n');
}

// --------------------------------------------------
// (sr, sc, d1, d2) 하나에 대해 구역을 나누고 인구 차이를 구해 정답을 갱신
//
//   area[r][c] : 그 칸이 속한 구역 번호 (1 = 마름모, 2~5 = 나머지)
// --------------------------------------------------
void calculate(int sr, int sc, int d1, int d2)
{
	int area[MAX][MAX] = { 0 };  // 호출할 때마다 0으로 새로 시작
	int sum[6] = { 0 };          // 구역별 인구 합 (1~5만 쓴다)
	int min, max;
	int start, end, left, right;

	// ----------------------------------------
	// 1) 마름모(경계선 + 내부)를 1번 구역으로 칠한다
	//
	// 첫 행은 (sr, sc) 한 칸.
	// 아래로 내려가며 왼쪽 경계는 -1씩(왼쪽으로), 오른쪽 경계는 +1씩(오른쪽으로) 벌어지다가
	// 각각 꼭짓점 열에 닿으면 방향을 뒤집어 다시 좁혀진다.
	// ----------------------------------------
	start = end = sc;
	left = -1;   // 왼쪽 경계의 이동량
	right = 1;   // 오른쪽 경계의 이동량

	for (int r = sr; r <= sr + d1 + d2; r++)
	{
		for (int c = start; c <= end; c++)
			area[r][c] = 1;

		start += left;
		end += right;

		// 왼쪽 꼭짓점 열에 닿았으면 이제부터 안쪽으로 좁힌다
		if (start == sc - d1)
			left = 1;

		// 오른쪽 꼭짓점 열에 닿았으면 이제부터 안쪽으로 좁힌다
		if (end == sc + d2)
			right = -1;
	}

	// ----------------------------------------
	// 2번 구역 (좌상) : r <= sr+d1-1, c <= sc
	//
	// 왼쪽에서 오른쪽으로 훑다가 마름모를 만나면 그 행은 더 볼 것이 없다 -> break
	// ----------------------------------------
	for (int r = 1; r <= N; r++)
	{
		for (int c = 1; c <= N; c++)
		{
			if (area[r][c] == 1)
				break;

			if ((1 <= r && r <= sr + d1 - 1) &&
				(1 <= c && c <= sc))
			{
				area[r][c] = 2;
			}
		}
	}

	// ----------------------------------------
	// 3번 구역 (우상) : r <= sr+d2, sc+1 <= c
	//
	// 마름모 오른쪽에도 이 구역의 칸이 남아 있으므로 건너뛰기만 한다 -> continue
	// ----------------------------------------
	for (int r = 1; r <= N; r++)
	{
		for (int c = 1; c <= N; c++)
		{
			if (area[r][c] == 1)
				continue;

			if ((1 <= r && r <= sr + d2) &&
				(sc + 1 <= c && c <= N))
			{
				area[r][c] = 3;
			}
		}
	}

	// ----------------------------------------
	// 4번 구역 (좌하) : sr+d1 <= r, c <= sc-d1+d2-1
	//
	// 왼쪽 구역이므로 마름모를 만나면 break
	// ----------------------------------------
	for (int r = 1; r <= N; r++)
	{
		for (int c = 1; c <= N; c++)
		{
			if (area[r][c] == 1)
				break;

			if ((sr + d1 <= r && r <= N) &&
				(1 <= c && c <= sc - d1 + d2 - 1))
			{
				area[r][c] = 4;
			}
		}
	}

	// ----------------------------------------
	// 5번 구역 (우하) : sr+d2+1 <= r, sc-d1+d2 <= c
	//
	// 오른쪽 구역이므로 continue
	// ----------------------------------------
	for (int r = 1; r <= N; r++)
	{
		for (int c = 1; c <= N; c++)
		{
			if (area[r][c] == 1)
				continue;

			if ((sr + d2 + 1 <= r && r <= N) &&
				(sc - d1 + d2 <= c && c <= N))
			{
				area[r][c] = 5;
			}
		}
	}

	// 구역 모양을 눈으로 확인하고 싶을 때
	// printMap(area);

	// 구역별 인구 합. 구역 번호를 그대로 인덱스로 쓴다.
	for (int r = 1; r <= N; r++)
	{
		for (int c = 1; c <= N; c++)
		{
			sum[area[r][c]] += MAP[r][c];
		}
	}

	min = INF;
	max = -INF;

	for (int i = 1; i <= 5; i++)
	{
		if (sum[i] < min) min = sum[i];
		if (sum[i] > max) max = sum[i];
	}

	if ((max - min) < minAnswer)
		minAnswer = max - min;
}

// --------------------------------------------------
// 가능한 모든 (sr, sc, d1, d2) 조합을 시도
//
// 기준점은 마름모가 아래로 뻗을 수 있어야 하므로 r은 N-2까지,
// 좌우로 벌어질 수 있어야 하므로 c는 2 ~ N-1 범위만 본다.
// --------------------------------------------------
void simulate()
{
	for (int r = 1; r <= N - 2; r++)
	{
		for (int c = 2; c <= N - 1; c++)
		{
			int d1 = 1;

			while (1)
			{
				// 왼쪽 아래 꼭짓점이 격자를 벗어나면 d1을 더 늘릴 수 없다
				if (MAP[r + d1][c - d1] == -1)
					break;

				int d2 = 1;

				while (1)
				{
					// 오른쪽 아래 꼭짓점 또는 맨 아래 꼭짓점이 격자를 벗어나면 중단
					if (MAP[r + d2][c + d2] == -1 ||
						MAP[r + d1 + d2][c + d2 - d1] == -1)
						break;

					calculate(r, c, d1, d2);

					d2++;
				}

				d1++;
			}
		}
	}
}

int main()
{
	// 이 문제는 테스트 케이스가 하나다
	// scanf("%d", &T);
	T = 1;

	for (int tc = 1; tc <= T; tc++)
	{
		input();

		minAnswer = INF;

		simulate();

		printf("%d\n", minAnswer);
	}

	return 0;
}
