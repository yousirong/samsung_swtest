/*
	[BOJ] 7576 - 토마토
	https://www.acmicpc.net/problem/7576

	■ 문제 요약
	  N x M 크기의 상자에 토마토가 들어 있다.

	     1 : 이미 익은 토마토
	     0 : 아직 익지 않은 토마토
	    -1 : 토마토가 들어 있지 않은 빈 칸

	  하루가 지나면 익은 토마토의 상하좌우에 있는 안 익은 토마토가 익는다.
	  모든 토마토가 익는 데 걸리는 최소 날짜를 출력한다.
	  처음부터 다 익어 있으면 0, 끝내 다 익지 못하면 -1.

	■ 풀이 방침 : 멀티 소스 BFS
	  익은 토마토가 여러 개일 수 있고, 이들이 "동시에" 퍼져 나간다는 점이 핵심이다.
	  하나씩 BFS를 돌려 최솟값을 취할 필요 없이,
	  처음부터 익어 있는 토마토를 전부 큐에 넣은 채로 BFS를 한 번만 돌리면 된다.

	  큐 안에 거리 0인 시작점이 여러 개 있는 상태로 출발하는 셈이라,
	  각 칸은 "가장 가까운 익은 토마토로부터의 거리"를 갖게 된다.
	  그게 바로 그 칸이 익는 날짜다.

	■ 구현 포인트
	  1) 별도의 visit이나 dist 배열 없이 MAP 한 장으로 끝낸다.
	     MAP[r][c]가 0인지 아닌지가 곧 "아직 안 익음 = 미방문"이기 때문에,
	     새로 익힐 때 값을 넣는 순간 자동으로 방문 표시가 된다.
	     그래서 조건 하나(MAP != 0)로 빈 칸, 이미 익은 칸, 방문한 칸이 모두 걸러진다.
	  2) 값은 "며칠째에 익었는가"를 1부터 세는 형태로 저장된다.
	     처음 익은 토마토가 1이므로 실제 경과 일수는 (최댓값 - 1)이다.
	  3) 바깥 테두리를 -1로 채워 두면 경계 검사를 생략할 수 있다.
	     여기서는 0이 "안 익은 토마토"라는 의미를 가지므로 테두리를 0으로 두면 안 되고,
	     반드시 -1(빈 칸)로 밀어야 한다.
*/

#include <stdio.h>

#define MAX (1000 + 100)

int M, N;               // M: 열 개수(가로), N: 행 개수(세로)  ※ 입력 순서가 M N 이다
int MAP[MAX][MAX];      // 상자 상태 겸 "익은 날짜" 기록판

// 좌표 한 쌍
struct RC
{
	int r;   // row (행)
	int c;   // col (열)
};

typedef struct RC RC;

RC queue[MAX * MAX];    // BFS용 큐 (한 칸이 최대 한 번 들어간다)

// 방향 배열: 상, 우, 하, 좌
int dr[] = { -1, 0, 1, 0 };
int dc[] = {  0, 1, 0,-1 };

// ---------------------------
// 입력
// ---------------------------
void input()
{
	scanf("%d %d", &M, &N);

	// 바깥 테두리를 -1(빈 칸)로 채워 둔다.
	// 0으로 두면 상자 밖이 "안 익은 토마토"로 읽혀 버리므로 반드시 -1이어야 한다.
	for (int r = 0; r <= N + 1; r++)
	{
		for (int c = 0; c <= M + 1; c++)
		{
			MAP[r][c] = -1;
		}
	}

	// 실제 상자 입력
	for (int r = 1; r <= N; r++)
	{
		for (int c = 1; c <= M; c++)
		{
			scanf("%d", &MAP[r][c]);
		}
	}
}

// ---------------------------
// 디버그용 출력
// ---------------------------
void printMap()
{
	for (int r = 1; r <= N; r++)
	{
		for (int c = 1; c <= M; c++)
			printf("%2d ", MAP[r][c]);
		putchar('\n');
	}
}

// ---------------------------
// 멀티 소스 BFS
//
// 처음부터 익어 있는 토마토를 모두 시작점으로 넣고 한 번에 퍼뜨린다.
// ---------------------------
void BFS()
{
	int rp, wp;   // rp: 꺼낼 위치, wp: 넣을 위치

	rp = wp = 0;

	// 시작점 모으기 : 값이 1인 칸을 전부 큐에 넣는다.
	// 이들이 큐 앞쪽에 나란히 들어가므로 같은 날짜에서 동시에 출발하는 효과가 난다.
	for (int r = 1; r <= N; r++)
	{
		for (int c = 1; c <= M; c++)
		{
			if (MAP[r][c] == 1)
			{
				queue[wp].r = r;
				queue[wp++].c = c;
			}
		}
	}

	while (rp < wp)
	{
		RC out = queue[rp++];

		// 상하좌우
		for (int i = 0; i < 4; i++)
		{
			int nr, nc;

			nr = out.r + dr[i];
			nc = out.c + dc[i];

			// 0이 아니면 전부 건너뛴다.
			//   -1  : 빈 칸(또는 상자 바깥)
			//   1이상: 이미 익었거나 이번 BFS에서 이미 익힌 칸(= 방문 완료)
			// 이 한 줄이 방문 검사까지 겸한다.
			if (MAP[nr][nc] != 0)
				continue;

			queue[wp].r = nr;
			queue[wp++].c = nc;

			// 값을 채우는 순간이 곧 방문 표시다.
			// 현재 칸이 x일째면 이웃은 x+1일째에 익는다.
			MAP[nr][nc] = MAP[out.r][out.c] + 1;
		}
	}
}

// ---------------------------
// 정답 계산
// ---------------------------
int getAnswer()
{
	int maxAnswer = 0;

	for (int r = 1; r <= N; r++)
	{
		for (int c = 1; c <= M; c++)
		{
			// 0이 남아 있다 = BFS가 닿지 못한 토마토가 있다
			if (MAP[r][c] == 0)
				return -1;

			// 가장 늦게 익은 칸의 값을 찾는다
			if (maxAnswer < MAP[r][c])
				maxAnswer = MAP[r][c];
		}
	}

	// 날짜를 1부터 셌으므로 실제 경과 일수는 최댓값 - 1.
	// 처음부터 전부 익어 있었다면 최댓값이 1이라 0이 나온다.
	return maxAnswer - 1;
}

// ---------------------------
// 메인
// ---------------------------
int main()
{
	input();

	BFS();

	printf("%d\n", getAnswer());

	return 0;
}
