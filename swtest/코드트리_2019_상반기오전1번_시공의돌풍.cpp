/*
	[코드트리] 2019 상반기 오전 1번 - 시공의 돌풍
	https://www.codetree.ai/training-field/frequent-problems/problems/heros-of-storm

	■ 문제 요약
	  N x M 격자에 먼지가 놓여 있고, 1열에 세로로 붙어 있는 두 칸이 공기청정기다(값 -1).
	  1초마다 아래 두 가지가 순서대로 일어난다.

	    1) 먼지 확산
	       먼지가 있는 모든 칸이 동시에 상하좌우로 (자기 먼지 / 5)씩 퍼진다(소수점 버림).
	       격자 밖이나 공기청정기 칸으로는 퍼지지 않는다.
	       퍼져 나간 방향의 개수만큼만 원래 칸에서 빠져나간다.

	    2) 공기청정기 작동
	       위쪽 청정기는 반시계 방향으로, 아래쪽 청정기는 시계 방향으로 바람을 돌린다.
	       바람이 지나가는 자리의 먼지가 통째로 한 칸씩 밀리고,
	       청정기 바로 오른쪽 칸에는 깨끗한 공기가 나오므로 먼지가 0이 된다.

	  time초 후 남아 있는 먼지의 총합을 출력한다.

	  (백준 17144 "미세먼지 안녕!"과 같은 문제다)

	■ 확산이 "동시에" 일어나게 하기
	  MAP을 바로 고치면서 퍼뜨리면, 방금 퍼진 먼지가 같은 초에 또 퍼져 나간다.
	  그래서 "이번 초에 새로 받은 양"만 tmpMAP에 따로 모았다가 마지막에 한꺼번에 더한다.

	    - 빠져나가는 양은 원래 칸에서 즉시 빼도 된다.
	      확산량 dust는 루프를 돌기 전 값(MAP[r][c] / 5)으로 고정되고,
	      그 칸은 이번 라운드에서 다시 확산 대상이 되지 않기 때문이다.
	    - 들어오는 양만 tmpMAP에 모으면 "동시 확산"이 정확히 재현된다.

	  퍼져 나간 방향 수 count를 세어 MAP[r][c] -= dust * count 로 빼는 것이 핵심이다.
	  네 방향 모두로 퍼지지 못하는 가장자리 칸은 그만큼 덜 잃는다.

	■ 공기청정기 : 값을 한 칸씩 당기기
	  바람의 순환은 사각 테두리를 따라 값을 한 칸 미는 것과 같다.
	  이 코드는 "각 칸이 자기 앞칸의 값을 가져온다"는 형태로 네 변을 차례로 훑는다.

	  위쪽 청정기(반시계)의 경우 바람은
	      청정기 행을 따라 오른쪽 -> 오른쪽 열을 따라 위로 -> 윗줄을 따라 왼쪽 -> 왼쪽 열을 따라 아래로
	  순환하므로, 값을 당기는 방향은 그 반대가 된다.

	  네 변을 훑는 순서가 중요하다. 각 모서리 값이 "다른 변에 넘겨진 뒤에" 덮이도록
	  왼쪽 열 -> 윗줄 -> 오른쪽 열 -> 청정기 행 순으로 처리해서
	  임시 배열 없이도 값이 사라지지 않게 만들어져 있다.

	  마지막으로 청정기 바로 오른쪽 칸을 0으로 만들고(깨끗한 공기),
	  청정기 칸 자체는 다시 -1로 되돌린다.

	  아래쪽 청정기(시계)는 위아래를 뒤집은 같은 코드다.
*/

#include <stdio.h>

#define MAX (50 + 10)
#define TORNADO_POSITION (-1)

int T;
int N, M, time;         // time : 시뮬레이션할 초
int MAP[MAX][MAX];      // 현재 먼지 상태 (-1은 공기청정기)
int tmpMAP[MAX][MAX];   // 이번 초에 "새로 들어온" 먼지만 모으는 배열

struct RC
{
	int r;
	int c;
};

typedef struct RC RC;

RC tornado[2];  // 공기청정기 두 칸. 입력을 위에서부터 읽으므로 [0]이 위쪽, [1]이 아래쪽이다.
int tcnt;

// 방향 배열: ↑, →, ↓, ←
int dr[] = { -1, 0, 1, 0 };
int dc[] = { 0, 1, 0, -1 };

// ---------------------------
// 입력
// ---------------------------
void input()
{
	scanf("%d %d %d", &N, &M, &time);

	tcnt = 0;

	for (int r = 1; r <= N; r++)
	{
		for (int c = 1; c <= M; c++)
		{
			scanf("%d", &MAP[r][c]);

			// 공기청정기 위치는 따로 기억해 둔다 (위쪽이 먼저 저장된다)
			if (MAP[r][c] == TORNADO_POSITION)
			{
				tornado[tcnt].r = r;
				tornado[tcnt++].c = c;
			}
		}
	}
}

// ---------------------------
// 디버그용 맵 출력
// ---------------------------
void printMap()
{
	for (int r = 1; r <= N; r++)
	{
		for (int c = 1; c <= M; c++)
			printf("%d ", MAP[r][c]);
		putchar('\n');
	}
	putchar('\n');
}

// ---------------------------
// 1단계 : 먼지 확산 (모든 칸이 동시에)
// ---------------------------
void diffusion()
{
	// 이번 초에 새로 들어올 양만 담을 배열을 비운다
	for (int r = 1; r <= N; r++)
		for (int c = 1; c <= M; c++)
			tmpMAP[r][c] = 0;

	for (int r = 1; r <= N; r++)
	{
		for (int c = 1; c <= M; c++)
		{
			// 먼지가 없는 칸(0)과 공기청정기 칸(-1)은 확산하지 않는다
			if (MAP[r][c] <= 0) continue;

			int dust, count;
			dust = count = 0;   // 네 방향 모두 막히면 dust가 0으로 남아 아무것도 빠지지 않는다

			for (int i = 0; i < 4; i++)
			{
				int nr = r + dr[i];
				int nc = c + dc[i];

				// 격자 밖으로는 퍼지지 않는다
				if (nr < 1 || nc < 1 || nr > N || nc > M) continue;

				// 공기청정기 칸으로도 퍼지지 않는다
				if (MAP[nr][nc] == TORNADO_POSITION) continue;

				// 확산량은 언제나 "이번 초 시작 시점의 값 / 5"다.
				// MAP[r][c]는 이 루프 안에서 바뀌지 않으므로 매번 같은 값이 나온다.
				dust = MAP[r][c] / 5;

				// 받는 쪽은 임시 배열에만 쌓아 둔다 (같은 초에 다시 퍼지지 않도록)
				tmpMAP[nr][nc] += dust;
				count++;
			}

			// 실제로 퍼져 나간 방향의 수만큼만 잃는다
			MAP[r][c] -= (dust * count);
		}
	}

	// 이번 초에 받은 양을 한꺼번에 반영
	for (int r = 1; r <= N; r++)
		for (int c = 1; c <= M; c++)
			MAP[r][c] += tmpMAP[r][c];
}

// ---------------------------
// 2단계 : 공기청정기 작동
//
// 값을 한 칸씩 당겨서 테두리를 회전시킨다.
// 네 변의 처리 순서가 정해져 있어야 모서리 값이 유실되지 않는다.
// ---------------------------
void cleaning()
{
	int up_r = tornado[0].r;     // 위쪽 청정기가 있는 행
	int down_r = tornado[1].r;   // 아래쪽 청정기가 있는 행

	// =====================================================
	// 위쪽 청정기 : 반시계 방향
	// 회전 구역은 (1,1) ~ (up_r, M)
	// =====================================================

	// 1) 왼쪽 열 : 위 -> 아래로 값이 내려온다 (바람은 청정기 쪽으로 들어간다)
	//    (up_r-1,1) <- (up_r-2,1) <- ... <- (2,1) <- (1,1)
	for (int r = up_r - 1; r > 1; r--)
		MAP[r][1] = MAP[r - 1][1];

	// 2) 윗줄 : 오른쪽 -> 왼쪽으로 값이 이동
	//    (1,1) <- (1,2) <- ... <- (1,M)
	for (int c = 1; c <= M - 1; c++)
		MAP[1][c] = MAP[1][c + 1];

	// 3) 오른쪽 열 : 아래 -> 위로 값이 올라간다
	//    (1,M) <- (2,M) <- ... <- (up_r,M)
	for (int r = 1; r <= up_r - 1; r++)
		MAP[r][M] = MAP[r + 1][M];

	// 4) 청정기 행 : 왼쪽 -> 오른쪽으로 값이 이동 (청정기에서 나온 바람 방향)
	//    (up_r,M) <- (up_r,M-1) <- ... <- (up_r,2) <- (up_r,1)
	for (int c = M; c > 1; c--)
		MAP[up_r][c] = MAP[up_r][c - 1];

	// 청정기에서 바로 나오는 칸은 깨끗한 공기다
	MAP[up_r][2] = 0;

	// 청정기 자리는 계속 -1로 표시해 둔다 (확산 판정에 쓰인다)
	MAP[up_r][1] = TORNADO_POSITION;

	// =====================================================
	// 아래쪽 청정기 : 시계 방향
	// 회전 구역은 (down_r,1) ~ (N, M). 위쪽과 위아래만 뒤집힌 형태다.
	// =====================================================

	// 1) 왼쪽 열 : 아래 -> 위로 값이 올라온다
	for (int r = down_r + 1; r <= N - 1; r++)
		MAP[r][1] = MAP[r + 1][1];

	// 2) 아랫줄 : 오른쪽 -> 왼쪽으로 값이 이동
	for (int c = 1; c <= M - 1; c++)
		MAP[N][c] = MAP[N][c + 1];

	// 3) 오른쪽 열 : 위 -> 아래로 값이 내려간다
	for (int r = N; r > down_r; r--)
		MAP[r][M] = MAP[r - 1][M];

	// 4) 청정기 행 : 왼쪽 -> 오른쪽으로 값이 이동
	for (int c = M; c > 1; c--)
		MAP[down_r][c] = MAP[down_r][c - 1];

	MAP[down_r][2] = 0;
	MAP[down_r][1] = TORNADO_POSITION;
}

// ---------------------------
// 남은 먼지 총합 (공기청정기의 -1은 빼고 센다)
// ---------------------------
int getAnswer()
{
	int sum = 0;

	for (int r = 1; r <= N; r++)
	{
		for (int c = 1; c <= M; c++)
		{
			if (MAP[r][c] != TORNADO_POSITION)
				sum += MAP[r][c];
		}
	}

	return sum;
}

int main()
{
	// 이 문제는 테스트 케이스가 하나다
	// scanf("%d", &T);
	T = 1;

	for (int tc = 1; tc <= T; tc++)
	{
		input();

		// 1초 = 확산 -> 청정기 작동
		for (int t = 0; t < time; t++)
		{
			diffusion();
			cleaning();
			// printMap();
		}

		printf("%d\n", getAnswer());
	}

	return 0;
}
