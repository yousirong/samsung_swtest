/*
	[BOJ] 1913 - 달팽이
	https://www.acmicpc.net/problem/1913

	■ 문제 요약
	  홀수 N과 숫자 K가 주어진다.
	  N x N 배열의 정가운데에 1을 놓고, 시계 반대 방향 나선(달팽이) 모양으로
	  N*N 까지 숫자를 채운 배열을 출력한다.
	  그다음 줄에 숫자 K가 놓인 칸의 (행, 열)을 출력한다.

	    N = 5 일 때
	      25 10 11 12 13
	      24  9  2  3 14
	      23  8  1  4 15
	      22  7  6  5 16
	      21 20 19 18 17

	■ 풀이 방침
	  나선을 "직선 구간(다리) 여러 개"로 쪼개서 채운다.

	    방향 순서   : 상 → 우 → 하 → 좌 → 상 → ... (4개 순환)
	    구간 길이   : 1, 1, 2, 2, 3, 3, 4, 4, ...  (두 구간마다 1씩 증가)

	  위 표에서 확인하면
	    상1(2) 우1(3) 하2(4,5) 좌2(6,7) 상3(8~10) 우3(11~13) 하4(14~17) 좌4(18~21) 상4(22~25)
	  로 정확히 맞아떨어진다.

	■ 주의할 점
	  1) 구간 개수는 2N-1개로 잡는다.
	     마지막 구간만 실제로는 N-1칸이면 충분한데 이 코드는 길이 N으로 진행해서
	     한 칸을 더 쓴다. 그런데 그 한 칸은 항상 0행(격자 바깥)이고
	     출력은 1행부터 하므로 결과에 아무 영향이 없다.
	     (마지막 구간의 방향은 N이 홀수인 한 언제나 "상"이라 위로 한 칸 넘칠 뿐이다.)
	  2) K의 좌표는 배열을 다 만든 뒤 다시 찾지 않고, 채우는 도중에 기록한다.
	     이때 비교 대상은 "아직 넣기 전의 index"이고 좌표는 "넣을 위치 (nr, nc)"다.
	  3) K == 1 인 경우는 구간 진입 전에 가운데에 이미 채우므로,
	     ansR/ansC를 시작할 때 가운데 좌표로 초기화해 둔 것이 그 처리를 겸한다.
*/

#include <stdio.h>

#define MAX (1000 + 100)

int N, K;              // N: 배열 크기(홀수), K: 좌표를 찾아야 하는 숫자
int MAP[MAX][MAX];     // 달팽이 모양으로 숫자를 채울 배열, 1-based

// 방향 배열: 상(0), 우(1), 하(2), 좌(3) 순으로 순환한다
int dr[] = { -1, 0, 1, 0 };
int dc[] = {  0, 1, 0,-1 };

// ---------------------------
// 완성된 배열 출력
// ---------------------------
void printMap()
{
	for (int r = 1; r <= N; r++)
	{
		for (int c = 1; c <= N; c++)
			printf("%d ", MAP[r][c]);
		putchar('\n');
	}
}

// ---------------------------
// 달팽이 배열 생성 + 정답 출력
// ---------------------------
void makesnail()
{
	int ansR, ansC;      // 숫자 K가 놓인 좌표
	int r, c;            // 현재 위치
	int direction;       // 현재 진행 방향 (dr/dc의 인덱스)
	int index;           // 다음에 채울 숫자
	int size;            // 이번 구간에서 이동할 칸 수

	// 시작점은 배열의 정가운데. K == 1 인 경우의 답도 여기서 미리 잡힌다.
	r = c = ansR = ansC = (N + 1) / 2;

	direction = 0;       // 첫 방향은 "상"
	index = 1;           // 첫 숫자는 1
	size = 0;            // 구간 길이는 아래 루프에서 1부터 늘어난다

	// 가운데 칸에 1을 채우고 index를 2로 올린다
	MAP[r][c] = index++;

	// 구간(직선으로 쭉 가는 한 다리)을 2N-1개 진행하면 배열이 전부 채워진다
	for (int i = 0; i < 2 * N - 1; i++)
	{
		// 구간 길이는 두 구간마다 1씩 증가 (1,1,2,2,3,3,...)
		// i가 짝수일 때만 늘려 주면 정확히 이 패턴이 된다
		if (i % 2 == 0)
			size++;

		// 현재 방향으로 size칸 직진하며 숫자를 채운다
		for (int s = 0; s < size; s++)
		{
			int nr, nc;

			// 다음 칸
			nr = r + dr[direction];
			nc = c + dc[direction];

			// 지금 채우려는 숫자가 K라면 그 좌표를 기록해 둔다.
			// index는 아직 MAP에 쓰기 전의 값이므로 여기서 비교해야 맞다.
			if (index == K)
			{
				ansR = nr;
				ansC = nc;
			}

			// 숫자를 쓰고 다음 숫자로
			MAP[nr][nc] = index++;

			// 현재 위치 갱신
			r = nr;
			c = nc;
		}

		// 다음 구간을 위해 방향 전환 : 상(0) -> 우(1) -> 하(2) -> 좌(3) -> 상(0)
		direction++;
		if (direction == 4)
			direction = 0;
	}

	// 완성된 배열
	printMap();

	// K의 좌표
	printf("%d %d", ansR, ansC);
}

// ---------------------------
// 메인
// ---------------------------
int main()
{
	scanf("%d %d", &N, &K);

	makesnail();

	return 0;
}
