void input()
{
	scanf("%d %d", &N, &M);              // 격자 크기 입력

	for (int r = 0; r < MAX; r++)        // 배열 전체를
		for (int c = 0; c < MAX; c++)
			MAP[r][c] = 0;               // 0으로 초기화 (범위 밖 처리용)

	for (int r = 0; r < N; r++)          // 실제 격자
		for (int c = 0; c < M; c++)
			scanf("%d", &MAP[r][c]);     // 칸의 수 입력
}

void printMap() //for debug
{
	for (int r = 0; r < N; r++)          // 모든 행
	{
		for (int c = 0; c < M; c++)      // 모든 열
			printf("%d ", MAP[r][c]);    // 값 출력
		putchar('\n');                   // 행 끝 줄바꿈
	}
	putchar('\n');                       // 빈 줄
}

int scan(int blockNum, int sr, int sc)
{
	int sum = 0;                         // 덮은 칸의 합

	for (int r = 0; r < 4; r++)          // 4x4 틀의 행
		for (int c = 0; c < 4; c++)      // 4x4 틀의 열
			sum += (MAP[sr + r][sc + c] * BLOCK[blockNum][r][c]);   // 덮는 칸만 더해진다

	return sum;                          // 합 반환
}

int main()
{
	//scanf("%d", &T);
	T = 1;                               // 테스트 케이스 1개
	for (int tc = 1; tc <= T; tc++)      // 테스트 케이스 반복
	{
		input();                         // 입력

		int maxAnswer = 0;               // 최대 합

		for (int r = 0; r < N; r++)      // 모든 시작 행
		{
			for (int c = 0; c < M; c++)  // 모든 시작 열
			{
				for (int k = 0; k < BLOCK_COUNT; k++)   // 모든 모양
				{
					int tmp = scan(k, r, c);   // 이 배치의 합

					if (maxAnswer < tmp) maxAnswer = tmp;   // 최댓값 갱신

				}
			}
		}
		printf("%d\n", maxAnswer);       // 결과 출력
	}
	return 0;                            // 프로그램 정상 종료
}
