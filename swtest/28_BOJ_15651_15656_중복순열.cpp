/*
	[BOJ] 15651 N과 M (3) / 15656 N과 M (7) - 중복순열
	https://www.acmicpc.net/problem/15651
	https://www.acmicpc.net/problem/15656

	■ 이 파일에 대하여
	  두 문제의 풀이가 아래위로 나란히 들어 있는 정리용 파일이다.
	  main과 전역 변수가 각각 하나씩 있으므로 한꺼번에 컴파일되지는 않는다.
	  제출하거나 돌려 볼 때는 필요한 쪽만 남기고 다른 쪽은 주석 처리해서 쓴다.

	■ 두 문제의 공통 주제 : 중복순열
	    - 중복 허용 : 같은 값을 몇 번이든 다시 골라도 된다
	    - 순서 구분 : 1 2 와 2 1 은 서로 다른 경우다

	  두 조건이 합쳐지면 "각 자리를 다른 자리와 완전히 독립적으로 채우면 된다"가 된다.
	  그래서 재귀가 가장 단순해진다.

	    - visit 배열이 필요 없다 (중복을 막을 이유가 없으므로)
	    - start 인자가 필요 없다 (순서를 없앨 이유가 없으므로)
	    - 매 자리에서 언제나 후보 전체(1 ~ N)를 처음부터 다시 돈다

	  총 경우의 수는 N^M 이다. (N, M <= 7 이라 최대 7^7 = 823,543)

	■ 두 문제의 차이
	    15651 : 후보가 1 ~ N 이라 i를 그대로 쓴다.
	    15656 : 후보가 입력으로 주어진 N개의 수라서 number[i]를 쓴다.
	            출력이 사전순이어야 하므로 입력받은 수를 먼저 오름차순 정렬해 둔다.
	            (재귀는 후보를 앞에서부터 훑으므로, 후보가 정렬돼 있으면 출력도 사전순이 된다)
*/

// ====================================================================
// BOJ 15651 - N과 M (3)
//
//   1부터 N까지의 수 중에서 중복을 허용해 길이 M인 수열을 모두 출력한다.
//
//   예) N = 3, M = 2
//       1 1 / 1 2 / 1 3 / 2 1 / 2 2 / 2 3 / 3 1 / 3 2 / 3 3   (총 3^2 = 9가지)
// ====================================================================

#include <stdio.h>

#define MAX (7 + 3)

int N, M;
int num_of_cases[MAX];   // 만들고 있는 수열. num_of_cases[0..M-1]이 완성되면 한 경우.

// 완성된 수열 한 줄 출력
void printCases()
{
	for (int i = 0; i < M; i++)
		printf("%d ", num_of_cases[i]);
	putchar('\n');
}

// 재귀로 중복순열 생성
//   depth : 지금 채우려는 자리 번호 (0부터 시작)
void DFS(int depth)
{
	// 자리를 M개 다 채웠다면 하나의 경우가 완성된 것
	if (depth == M)
	{
		printCases();
		return;
	}

	// 이 자리에는 1 ~ N 중 무엇이든 올 수 있다.
	// 앞 자리에서 무엇을 골랐는지와 전혀 무관하다.
	for (int i = 1; i <= N; i++)
	{
		num_of_cases[depth] = i;

		// 중복이 허용되므로 사용 표시(visit)도, 되돌리기도 필요 없다.
		// 다음 호출에서 이 자리 값을 덮어쓰기 때문에 따로 정리할 것이 없다.
		DFS(depth + 1);
	}
}

int main()
{
	scanf("%d %d", &N, &M);

	DFS(0);   // 0번째 자리부터 채우기 시작

	return 0;
}

// ====================================================================
// BOJ 15656 - N과 M (7)
//
//   입력으로 주어진 N개의 수 중에서 중복을 허용해 길이 M인 수열을 모두 출력한다.
//   출력은 사전순이어야 한다.
//
//   예) 입력 숫자 9 7 1  ->  정렬 후 1 7 9, M = 2 이면
//       1 1 / 1 7 / 1 9 / 7 1 / 7 7 / 7 9 / 9 1 / 9 7 / 9 9
//
//   15651과 재귀 구조는 완전히 같고, 넣는 값이 i 대신 number[i]라는 점만 다르다.
// ====================================================================

#include <stdio.h>

#define MAX (7 + 3)

int N, M;

int num_of_cases[MAX];   // 만들고 있는 수열
int number[MAX];         // 후보로 주어진 수들 (1-based로 저장)

// 완성된 수열 한 줄 출력
void printCases()
{
	for (int i = 0; i < M; i++)
		printf("%d ", num_of_cases[i]);
	putchar('\n');
}

// 재귀로 중복순열 생성
void DFS(int depth)
{
	if (depth == M)
	{
		printCases();
		return;
	}

	// 이 자리에는 후보 전체가 다시 올 수 있다
	for (int i = 1; i <= N; i++)
	{
		// 15651과 유일하게 다른 줄 : 인덱스가 아니라 실제 입력값을 담는다
		num_of_cases[depth] = number[i];

		DFS(depth + 1);
	}
}

int main()
{
	scanf("%d %d", &N, &M);

	// 후보 수 입력
	for (int i = 1; i <= N; i++)
		scanf("%d", &number[i]);

	// 사전순 출력을 위한 오름차순 정렬 (선택 정렬)
	// 재귀가 후보를 앞에서부터 훑으므로, 후보만 정렬해 두면 출력도 자동으로 사전순이 된다.
	for (int i = 1; i <= N - 1; i++)
	{
		for (int k = i + 1; k <= N; k++)
		{
			if (number[i] > number[k])
			{
				int tmp = number[i];
				number[i] = number[k];
				number[k] = tmp;
			}
		}
	}

	DFS(0);

	return 0;
}
